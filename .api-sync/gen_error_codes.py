#!/usr/bin/env python3
"""Generates src/blindpay/error_codes.py (typed API error codes) from the spec's `Errors` tag.

The tag's description holds the error-code table, one row per code:

    | `QUOTES_EXPIRED` | 400 | actionable | This quote has expired. Request a new quote and try again. |

Each row becomes an `ErrorCode` member plus an `ErrorCodeInfo(status, retry)` entry. Stdlib only, deterministic.
Usage:

    python3 .api-sync/gen_error_codes.py --spec <openapi.json>           # write the module
    python3 .api-sync/gen_error_codes.py --spec <openapi.json> --check   # exit 1 if it would change

It fails (exit 2) when the table has no rows, a row doesn't parse, a code repeats, a code isn't a valid Python
identifier, or a retry class is unknown, so a reshaped table can't silently produce an empty enum.
"""

import argparse
import json
import keyword
import re
import sys
import textwrap
from pathlib import Path
from typing import Any, Dict, List, Tuple

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "src" / "blindpay" / "error_codes.py"
TAG = "Errors"
RETRY_CLASSES = ("retryable", "terminal", "actionable")
ROW = re.compile(
    r"^\|\s*`(?P<code>[^`]+)`\s*\|\s*(?P<status>\d{3})\s*\|\s*(?P<retry>[a-z]+)\s*\|\s*(?P<desc>.*?)\s*\|$"
)

Row = Tuple[str, int, str, str]

HEADER = '''"""BlindPay API error codes: each code's typical HTTP status and retry class.

GENERATED by .api-sync/gen_error_codes.py from the public OpenAPI spec's `Errors` tag. Do not edit by hand.

``ErrorResponse["code"]`` stays a plain ``str``, so codes added to the API after this SDK version still arrive.
``ErrorCode`` is a ``str`` enum, so ``error["code"] == ErrorCode.QUOTES_EXPIRED`` works on that plain string.
Prefer ``code`` over the legacy ``message`` string; some error bodies (idempotency conflicts) carry no ``code``.
"""

from dataclasses import dataclass
from enum import Enum
from typing import Dict, Optional, Union

__all__ = ["ErrorCode", "ErrorCodeInfo", "RetryClass", "error_code_info"]


class RetryClass(str, Enum):
    """How the API classifies an error code.

    - ``RETRYABLE``: the same request can be sent again as is.
    - ``TERMINAL``: don't retry.
    - ``ACTIONABLE``: the request succeeds only after you fix something (fund a balance, correct bank details).
    - ``UNKNOWN``: no code, an ``SDK_*`` code, or a code this SDK version doesn't know.

    This is the API's classification. ``ErrorResponse["retryable"]`` is the SDK's transport decision for this exact
    request (a mutation that got a 5xx is never retryable, whatever its code says).
    """

    RETRYABLE = "retryable"
    TERMINAL = "terminal"
    ACTIONABLE = "actionable"
    UNKNOWN = "unknown"

    def __str__(self) -> str:
        return self.value


@dataclass(frozen=True)
class ErrorCodeInfo:
    """What the spec's error table says about a code."""

    status: int
    """The HTTP status this code typically responds with. Each endpoint's error table has the exact one."""
    retry: RetryClass


class ErrorCode(str, Enum):
    """Every error code in the public API spec. Compare with ``ErrorResponse["code"]``, which stays a ``str``."""

    def __str__(self) -> str:
        return self.value

'''

FOOTER = '''

def error_code_info(code: Union[ErrorCode, str, None]) -> Optional[ErrorCodeInfo]:
    """Status and retry class for ``code``; ``None`` for no code, an ``SDK_*`` code, or a code this SDK version
    doesn't know."""
    return _INFO.get(code) if code is not None else None
'''


class TableError(Exception):
    pass


def errors_table(spec: Dict[str, Any]) -> List[Row]:
    tags = [tag for tag in spec.get("tags", []) if tag.get("name") == TAG]
    if not tags:
        raise TableError(f"the spec has no `{TAG}` tag")
    rows: List[Row] = []
    seen: set[str] = set()
    for line in str(tags[0].get("description", "")).splitlines():
        line = line.strip()
        if not line.startswith("| `"):
            continue
        match = ROW.match(line)
        if not match:
            raise TableError(f"unparseable error-code row: {line}")
        code, retry = match["code"], match["retry"]
        if not code.isidentifier() or keyword.iskeyword(code) or not code.isupper():
            raise TableError(f"error code {code!r} isn't an UPPER_SNAKE Python identifier")
        if code in seen:
            raise TableError(f"error code {code} appears twice")
        if retry not in RETRY_CLASSES:
            raise TableError(f"error code {code} has unknown retry class {retry!r}")
        seen.add(code)
        rows.append((code, int(match["status"]), retry, match["desc"]))
    if not rows:
        raise TableError(f"the `{TAG}` tag has no error-code rows")
    return sorted(rows)


def docstring(text: str) -> str:
    text = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"').strip()
    lines = textwrap.wrap(text, width=110) or [""]
    if len(lines) == 1:
        return f'    """{lines[0]}"""\n'
    body = "\n".join(f"    {line}" if i else line for i, line in enumerate(lines))
    return f'    """{body}"""\n'


def build(rows: List[Row]) -> str:
    members = "".join(f'    {code} = "{code}"\n{docstring(desc)}' for code, _, _, desc in rows)
    info = "".join(
        f'    "{code}": ErrorCodeInfo({status}, RetryClass.{retry.upper()}),\n' for code, status, retry, _ in rows
    )
    return HEADER + members + "\n\n_INFO: Dict[str, ErrorCodeInfo] = {\n" + info + "}\n" + FOOTER


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--spec", required=True, type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        rows = errors_table(json.loads(args.spec.read_text()))
    except TableError as error:
        print(f"gen_error_codes: {error}", file=sys.stderr)
        return 2
    source = build(rows)
    if args.check:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != source:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date; re-run without --check")
            return 1
        print(f"error codes: up to date ({len(rows)} codes)")
        return 0
    OUTPUT.write_text(source)
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(rows)} codes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
