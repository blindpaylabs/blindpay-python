#!/usr/bin/env python3
"""Generates src/blindpay/webhook_events.py (typed webhook payloads) from the spec's top-level `webhooks`.

Each event's request-body schema (e.g. PayoutNewWebhookOut) becomes a TypedDict whose `webhook_event` field is a
single-value Literal, so `WebhookEvent` is a union that type checkers narrow on `event["webhook_event"]`.
Stdlib only, deterministic. Usage:

    python3 .api-sync/gen_webhook_events.py --spec <openapi.json>           # write the module
    python3 .api-sync/gen_webhook_events.py --spec <openapi.json> --check   # exit 1 if it would change

Mapping: required keys stay required, others are NotRequired; nullable types are Optional; string enums are typed
`str` (responses must tolerate values the SDK doesn't know yet); nested objects become their own TypedDicts named
after their owner and property (e.g. `PayoutCompleteWebhookEventTrackingPayment`), so names stay stable across syncs.
"""

import argparse
import json
import keyword
import re
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

ROOT = Path(__file__).resolve().parent.parent

# Provider names stay out of the public SDK surface (blindpay-v2 AGENTS.md):
# no typed fields named after one. They still arrive at runtime;
# they're just not modelled. Reason recorded for each: "provider-named field; pending blindpay-v2 decision".
PROVIDER_NAMED = re.compile(r"^(checkbook|onemoney|circle|aiprise|infinitus|jpm)_")
OUTPUT = ROOT / "src" / "blindpay" / "webhook_events.py"

HEADER = '''"""Typed BlindPay webhook payloads, one TypedDict per event.

GENERATED by .api-sync/gen_webhook_events.py from the public OpenAPI spec's `webhooks` section. Do not edit by hand.

Narrow a ``WebhookEvent`` on its ``webhook_event`` key. Events this SDK version doesn't know yet arrive as
``UnknownWebhookEvent`` (all of their keys are still present at runtime). String enums are typed ``str`` so new
values never break decoding.
"""

from typing import Any, Dict, List, Literal, Optional, Union

from typing_extensions import NotRequired, TypedDict

'''


def pascal(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[^0-9A-Za-z]+", name) if part)


class Generator:
    def __init__(self, spec: Dict[str, Any]) -> None:
        self.schemas: Dict[str, Any] = spec.get("components", {}).get("schemas", {})
        self.webhooks: Dict[str, Any] = spec.get("webhooks", {})
        self.classes: List[str] = []
        self.names: set[str] = set()

    def resolve(self, schema: Dict[str, Any]) -> Dict[str, Any]:
        while "$ref" in schema:
            schema = self.schemas[schema["$ref"].split("/")[-1]]
        if "allOf" in schema and len(schema["allOf"]) == 1:
            merged = dict(self.resolve(schema["allOf"][0]))
            merged.update({k: v for k, v in schema.items() if k != "allOf"})
            return merged
        return schema

    @staticmethod
    def split_null(schema: Dict[str, Any]) -> Tuple[Dict[str, Any], bool]:
        nullable = False
        types = schema.get("type")
        if isinstance(types, list):
            nullable = "null" in types
            rest = [t for t in types if t != "null"]
            schema = {**schema, "type": rest[0] if len(rest) == 1 else rest}
        if "enum" in schema and None in schema["enum"]:
            nullable = True
            schema = {**schema, "enum": [v for v in schema["enum"] if v is not None]}
        for combinator in ("anyOf", "oneOf"):
            if combinator in schema:
                options = schema[combinator]
                non_null = [o for o in options if o.get("type") != "null"]
                if len(non_null) < len(options):
                    nullable = True
                kinds = {o.get("type") for o in non_null}
                if len(non_null) == 1:
                    schema = {**{k: v for k, v in schema.items() if k != combinator}, **non_null[0]}
                elif len(kinds) == 1 and next(iter(kinds)) in ("string", "integer", "number", "boolean"):
                    # e.g. a date-time string or "" / a 9-digit string: one wire type, several formats.
                    schema = {**{k: v for k, v in schema.items() if k != combinator}, "type": next(iter(kinds))}
        return schema, nullable

    def annotation(self, schema: Dict[str, Any], hint: str) -> str:
        schema, nullable = self.split_null(self.resolve(schema))
        schema = self.resolve(schema)
        base = self.base_annotation(schema, hint)
        return f"Optional[{base}]" if nullable else base

    def base_annotation(self, schema: Dict[str, Any], hint: str) -> str:
        kind = schema.get("type")
        if "anyOf" in schema or "oneOf" in schema or isinstance(kind, list):
            return "Any"
        if kind == "string":
            return "str"
        if kind == "integer":
            return "int"
        if kind == "number":
            return "float"
        if kind == "boolean":
            return "bool"
        if kind == "array":
            return f"List[{self.annotation(schema.get('items', {}), hint)}]"
        if kind == "object" or "properties" in schema:
            if not schema.get("properties"):
                return "Dict[str, Any]"
            return self.typed_dict(schema, hint)
        return "Any"

    def typed_dict(self, schema: Dict[str, Any], name: str, discriminator: Optional[str] = None) -> str:
        properties: Dict[str, Any] = schema.get("properties", {})
        required = set(schema.get("required", []))
        fields: List[Tuple[str, str]] = []
        for prop, prop_schema in properties.items():
            if PROVIDER_NAMED.match(prop):
                continue
            if prop == "webhook_event" and discriminator is not None:
                annotation = f'Literal["{discriminator}"]'
            else:
                annotation = self.annotation(prop_schema, f"{name}{pascal(prop)}")
            if prop not in required:
                annotation = f"NotRequired[{annotation}]"
            fields.append((prop, annotation))
        if name in self.names:
            raise SystemExit(f"generated TypedDict name collision: {name}")
        self.names.add(name)
        self.classes.append(self.render(name, fields))
        return name

    @staticmethod
    def render(name: str, fields: List[Tuple[str, str]]) -> str:
        if any(keyword.iskeyword(f) or not f.isidentifier() for f, _ in fields):
            body = "".join(f'        "{f}": {a},\n' for f, a in fields)
            return f'{name} = TypedDict(\n    "{name}",\n    {{\n{body}    }},\n)\n'
        body = "".join(f"    {f}: {a}\n" for f, a in fields) or "    pass\n"
        return f"class {name}(TypedDict):\n{body}"

    def build(self) -> str:
        events: List[Tuple[str, str]] = []
        for event in sorted(self.webhooks):
            operation = self.webhooks[event].get("post", {})
            schema = operation["requestBody"]["content"]["application/json"]["schema"]
            events.append((event, self.typed_dict(self.resolve(schema), f"{pascal(event)}WebhookEvent", event)))
        self.classes.append(
            "class UnknownWebhookEvent(TypedDict):\n"
            '    """An event this SDK version doesn\'t model yet. '
            'Every key of the payload is present at runtime."""\n\n'
            "    webhook_event: str\n"
        )
        union = "".join(f"    {cls},\n" for _, cls in events) + "    UnknownWebhookEvent,\n"
        names = "".join(f'    "{event}",\n' for event, _ in events)
        mapping = "".join(f'    "{event}": {cls},\n' for event, cls in events)
        footer = (
            f"WebhookEvent = Union[\n{union}]\n\n"
            f"WebhookEventName = Literal[\n{names}]\n\n"
            "WEBHOOK_EVENT_TYPES: Dict[str, Any] = {\n" + mapping + "}\n"
            '"""Known event name -> its TypedDict."""\n'
        )
        exported = sorted(
            self.names | {"UnknownWebhookEvent", "WebhookEvent", "WebhookEventName", "WEBHOOK_EVENT_TYPES"}
        )
        all_block = "__all__ = [\n" + "".join(f'    "{name}",\n' for name in exported) + "]\n\n\n"
        return HEADER + all_block + "\n\n".join(self.classes) + "\n\n" + footer


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--spec", required=True, type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = Generator(json.loads(args.spec.read_text())).build()
    if args.check:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != source:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date; re-run without --check")
            return 1
        print("webhook events: up to date")
        return 0
    OUTPUT.write_text(source)
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
