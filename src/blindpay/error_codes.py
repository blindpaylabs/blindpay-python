"""BlindPay API error codes: each code's typical HTTP status and retry class.

GENERATED by .api-sync/gen_error_codes.py from the public OpenAPI spec's `Errors` tag. Do not edit by hand.

``ErrorResponse["code"]`` stays a plain ``str``, so codes added to the API after this SDK version still arrive.
``ErrorCode`` is a ``str`` enum, so ``error["code"] == ErrorCode.QUOTES_EXPIRED`` works on that plain string.
Prefer ``code`` over the legacy ``message`` string; some error bodies (idempotency conflicts) carry no ``code``.
"""

from dataclasses import dataclass
from enum import Enum
from typing import Dict, Optional, Union

__all__ = ["ErrorCode", "ErrorCodeInfo", "RetryClass", "error_code_info"]


class RetryClass(str, Enum):
    """How the API classifies an error code.

    - ``RETRYABLE``: the same request can be sent again as is.
    - ``TERMINAL``: don't retry.
    - ``ACTIONABLE``: the request succeeds only after you fix something (fund a balance, correct bank details).
    - ``UNKNOWN``: no code, an ``SDK_*`` code, or a code this SDK version doesn't know.

    This is the API's classification. ``ErrorResponse["retryable"]`` is the SDK's transport decision for this exact
    request (it never auto-retries a mutation that got a 5xx, whatever its code says).
    """

    RETRYABLE = "retryable"
    TERMINAL = "terminal"
    ACTIONABLE = "actionable"
    UNKNOWN = "unknown"

    def __str__(self) -> str:
        return self.value


@dataclass(frozen=True)
class ErrorCodeInfo:
    """What the spec's error table says about a code."""

    status: int
    """The HTTP status this code typically responds with. Each endpoint's error table has the exact one."""
    retry: RetryClass


